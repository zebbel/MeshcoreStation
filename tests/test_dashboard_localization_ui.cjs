const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const assets = 'meshcorestation/web/assets/';
const dom = new JSDOM('<html lang="de"><body></body></html>', {runScripts:'outside-only',url:'http://localhost/'});
const {window} = dom;
const en = JSON.parse(fs.readFileSync('meshcorestation/web/locales/en.json'));
const de = JSON.parse(fs.readFileSync('meshcorestation/web/locales/de.json'));
delete de['Repeater Statistics'];
window.MeshcoreStationCatalogs = {en, de};
window.eval(fs.readFileSync(assets+'01_i18n.js', 'utf8'));
const {t, html, translatedError} = window.MeshcoreStationI18n;
assert.equal(t('Settings'), 'Einstellungen');
assert.equal(t('Repeater Statistics'), 'Repeater Statistics');
assert.equal(t('Unknown entry'), 'Unknown entry');
assert.equal(t('Connected companion: {0}', 'Settings'), 'Verbundener Companion: Settings');
assert.equal(translatedError('Expected 1–20 in steps of 2.'), 'Erwarteter Bereich: 1–20 in Schritten von 2.');
assert.match(translatedError('The server query budget was reached during classify. Refresh this period to resume classification. Recording continues; saved data is preserved.'), /Klassifizierung/);
const host = window.document.createElement('div');
host.innerHTML = html('<button id="close" aria-label="Close settings" value="Save">Save</button><code>Save</code>');
assert.equal(host.querySelector('button').textContent, 'Speichern');
assert.equal(host.querySelector('button').getAttribute('aria-label'), 'Einstellungen schließen');
assert.equal(host.querySelector('button').value, 'Save');
assert.equal(host.querySelector('code').textContent, 'Save');
window.close();
console.log('Catalog lookup, fallback, formatted errors, and safe markup translation passed.');
