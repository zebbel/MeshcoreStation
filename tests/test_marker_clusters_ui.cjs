const {JSDOM}=require('jsdom'),fs=require('node:fs'),assert=require('node:assert/strict');
const dom=new JSDOM('<div id="map"></div>',{runScripts:'outside-only',pretendToBeVisual:true,url:'http://localhost/'}),w=dom.window;
w.matchMedia=()=>({matches:true});
for(const file of ['vendor/leaflet.js','vendor/leaflet.markercluster.js','aa_marker_clusters.js'])w.eval(fs.readFileSync('meshcorestation/web/assets/'+file,'utf8'));
const L=w.L,el=w.document.getElementById('map');
Object.defineProperty(el,'clientWidth',{value:800});Object.defineProperty(el,'clientHeight',{value:600});L.Browser.svg=true;
const map=L.map(el,{maxZoom:19,zoomAnimation:false}).setView([51,10],5);
const group=w.meshcorestationMarkerClusters(map);
const marker=position=>L.marker(position,{icon:L.divIcon({html:'R'})}).bindPopup('Repeater details',{autoPan:false}).addTo(group);
const a=marker([51,10]),b=marker([51,10.001]),c=marker([51,10]);
let cluster=group.getVisibleParent(a);assert.equal(cluster.getChildCount(),3);
const icon=group.options.iconCreateFunction(cluster);assert.equal(icon.options.html.textContent,'3');
assert(icon.options.html.getAttribute('aria-label').includes('3 repeaters'));
map.setZoom(16);
assert(group.getVisibleParent(b)===b,'Markers with enough room must separate before maximum zoom');
map.setZoom(19);
assert(group.getVisibleParent(b)===b,'Separated markers must become individual markers when zoomed in');
cluster=group.getVisibleParent(a);assert.equal(cluster.getChildCount(),2);
cluster.spiderfy();assert(a._spiderLeg&&c._spiderLeg,'Coincident markers must spread apart');
assert.notDeepEqual(a.getLatLng(),c.getLatLng());
cluster.unspiderfy();map.setZoom(5);assert.equal(group.getVisibleParent(a).getChildCount(),3);
group.fire('click',{layer:group.getVisibleParent(a),originalEvent:{}});
assert(map.getZoom()>5,'Clicking a cluster must zoom in');
map.setZoom(5);
w.meshcorestationRevealMarker(map,group,a,()=>true);
setTimeout(()=>{try{assert(map.hasLayer(a),'Search must reveal a clustered marker');assert(a.isPopupOpen());map.remove();dom.window.close();console.log('Real Leaflet clustering, zoom, overlapping markers and popup reveal passed.');}catch(e){console.error(e);process.exit(1);}},500);
