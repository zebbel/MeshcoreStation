const fs=require('fs'),assert=require('assert'),{JSDOM}=require('jsdom');
const html=fs.readFileSync('meshcorestation/web/rooms.html','utf8');
const dom=new JSDOM(html,{url:'http://localhost/rooms',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window, requests=[];
const room={id:1,name:'Community',enabled:1,scope_key:'',public_key:'aa'.repeat(32),contact_uri:'meshcore://contact/add?type=3',members:[{public_key:'bb'.repeat(32),role:'writer'}],posts:[{timestamp:1000,author:'bb'.repeat(32),text:'<img src=x onerror=alert(1)>'}]};
w.fetch=async(url,options)=>{
 const body=options.body?JSON.parse(options.body):null; requests.push(body);
 if(url==='/api/companion/contacts')return {ok:true,json:async()=>({ok:true,contacts:[{name:'Alice',type:1,public_key:'bb'.repeat(32)},{name:'Bob',type:1,public_key:'cc'.repeat(32)},{name:'Repeater',type:2,public_key:'dd'.repeat(32)}]})};
 if(body?.action==='qr')return {ok:true,json:async()=>({ok:true,image:'data:image/svg+xml;base64,PHN2Zy8+'})};
 return {ok:true,json:async()=>({ok:true,rooms:[room],status:{running:true,sessions:1,dropped_packets:0}})};
};
w.setInterval=()=>0;
w.eval(fs.readFileSync('meshcorestation/web/assets/rooms.js','utf8'));
(async()=>{
 await new Promise(r=>setTimeout(r,10));
 assert(!w.document.getElementById('details').hidden);
 assert.equal(w.document.querySelectorAll('#posts img').length,0);
 assert(w.document.getElementById('posts').textContent.includes('<img'));
 w.document.getElementById('show-qr').click();await new Promise(r=>setTimeout(r,10));
 assert(!w.document.getElementById('room-qr').hidden);
 assert(w.document.getElementById('room-qr-image').src.startsWith('data:image/svg+xml'));
 assert.deepEqual(requests.at(-1),{action:'qr',room:1});
 w.document.getElementById('load-contacts').click();await new Promise(r=>setTimeout(r,10));
 const picker=w.document.getElementById('contact-picker');
 assert.equal(picker.options.length,3);assert(picker.options[1].disabled);
 picker.value='cc'.repeat(32);picker.dispatchEvent(new w.Event('change'));
 assert.equal(w.document.getElementById('member-key').value,'cc'.repeat(32));
 w.document.getElementById('role').value='reader';
 w.document.getElementById('grant').dispatchEvent(new w.Event('submit',{cancelable:true}));
 await new Promise(r=>setTimeout(r,10));
 assert.deepEqual(requests.at(-1),{room:1,action:'grant',key:'cc'.repeat(32),role:'reader'});
 const text=w.document.getElementById('text');text.value='From dashboard';
 w.document.getElementById('post').dispatchEvent(new w.Event('submit',{cancelable:true}));
 await new Promise(r=>setTimeout(r,10));
 assert.deepEqual(requests.at(-1),{room:1,action:'post',text:'From dashboard'});
 assert.equal(text.value,'');
 w.fetch=async()=>({ok:false,json:async()=>({ok:false,error:'Room disabled'})});
 text.value='Keep draft';w.document.getElementById('post').dispatchEvent(new w.Event('submit',{cancelable:true}));
 await new Promise(r=>setTimeout(r,10));
 assert.equal(text.value,'Keep draft');assert.equal(w.document.getElementById('error').textContent,'Room disabled');
 dom.window.close();console.log('Room UI controls and safe message rendering passed');
})().catch(e=>{console.error(e);process.exit(1);});
