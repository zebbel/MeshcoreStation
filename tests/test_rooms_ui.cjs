const fs=require('fs'),assert=require('assert'),{JSDOM}=require('jsdom');
const html=fs.readFileSync('meshcorestation/web/rooms.html','utf8');
const dom=new JSDOM(html,{url:'http://localhost/rooms',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window, requests=[];
const room={id:1,name:'Community',enabled:1,is_bot:0,auth_revision:1,public_key:'aa'.repeat(32),contact_uri:'meshcore://contact/add?type=3',members:[{public_key:'bb'.repeat(32),role:'writer'},{public_key:'ee'.repeat(32),role:'reader'}],posts:[{timestamp:1000,author:'bb'.repeat(32),text:'<img src=x onerror=alert(1)>'}]};
w.fetch=async(url,options)=>{
 const body=options.body?JSON.parse(options.body):null; requests.push(body);
 if(url==='/api/companion/contacts')return {ok:true,json:async()=>({ok:true,contacts:[{name:'Alice',type:1,public_key:'bb'.repeat(32)},{name:'Bob',type:1,public_key:'cc'.repeat(32)},{name:'Repeater',type:2,public_key:'dd'.repeat(32)}]})};
 if(body?.action==='grant')room.members.find(m=>m.public_key===body.key).role=body.role;
 if(body?.action==='qr')return {ok:true,json:async()=>({ok:true,image:'data:image/svg+xml;base64,PHN2Zy8+'})};
 return {ok:true,json:async()=>({ok:true,rooms:[room],status:{running:true,sessions:1,dropped_packets:0}})};
};
w.setInterval=()=>0;
w.eval(fs.readFileSync('meshcorestation/web/assets/rooms.js','utf8'));
